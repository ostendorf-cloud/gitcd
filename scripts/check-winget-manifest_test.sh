# Table driven tests for check-winget-manifest.sh: one accepted manifest set,
# in the shape goreleaser generates, and a list of altered sets that must each
# be rejected. The real snapshot manifests are accepted by "task test:winget",
# which runs the same script on them.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
validator="${script_dir}/check-winget-manifest.sh"
# An explicit template, because macOS mktemp ignores TMPDIR without one.
work="$(mktemp -d "${TMPDIR:-/tmp}/check-winget-manifest-test.XXXXXXXX")"
finished=no
# An old bash can stop a script on an expansion it does not know and still
# exit 0, so a run that did not reach its last line fails here.
trap 'rm -rf "${work}"; if [ "${finished}" != yes ]; then if [ "${failures:-0}" -eq 0 ]; then echo "test script stopped before its last line" >&2; fi; exit 1; fi' EXIT

tag="v1.0.0"
failures=0
manifest="${work}/manifest"
checksums="${work}/checksums.txt"
id="OstendorfCloud.gitcd"

sha_amd64="$(printf '%064d' 0 | tr 0 1)"
sha_arm64="$(printf '%064d' 0 | tr 0 2)"
sha_other="$(printf '%064d' 0 | tr 0 3)"
base_url="https://github.com/ostendorf-cloud/gitcd/releases/download/${tag}"

checksums_base="$(
  cat <<EOF
${sha_other}  gitcd_darwin_amd64.tar.gz
${sha_other}  gitcd_linux_amd64.tar.gz
${sha_amd64}  gitcd_windows_amd64.zip
${sha_arm64}  gitcd_windows_arm64.zip
EOF
)"

version_base="$(
  cat <<EOF
# This file was generated by GoReleaser. DO NOT EDIT.
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.1.28.0.schema.json
PackageIdentifier: OstendorfCloud.gitcd
PackageVersion: 1.0.0
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.28.0
EOF
)"

locale_base="$(
  cat <<EOF
# This file was generated by GoReleaser. DO NOT EDIT.
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.1.28.0.schema.json
PackageIdentifier: OstendorfCloud.gitcd
PackageVersion: 1.0.0
PackageLocale: en-US
Publisher: Ostendorf Cloud
PublisherUrl: https://github.com/ostendorf-cloud
PublisherSupportUrl: https://github.com/ostendorf-cloud/gitcd/issues
PackageName: gitcd
PackageUrl: https://github.com/ostendorf-cloud/gitcd
License: Apache-2.0
LicenseUrl: https://github.com/ostendorf-cloud/gitcd/blob/main/LICENSE
ShortDescription: Clone repositories into a predictable layout and apply a git identity profile per remote
Moniker: gitcd
Tags:
  - git
  - cli
  - developer-tools
ManifestType: defaultLocale
ManifestVersion: 1.28.0
EOF
)"

installer_base="$(
  cat <<EOF
# This file was generated by GoReleaser. DO NOT EDIT.
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.1.28.0.schema.json
PackageIdentifier: OstendorfCloud.gitcd
PackageVersion: 1.0.0
InstallerLocale: en-US
InstallerType: zip
ReleaseDate: "2026-11-16"
Installers:
  - Architecture: arm64
    NestedInstallerType: portable
    NestedInstallerFiles:
      - RelativeFilePath: gitcd.exe
        PortableCommandAlias: gitcd
    InstallerUrl: ${base_url}/gitcd_windows_arm64.zip
    InstallerSha256: ${sha_arm64}
    UpgradeBehavior: uninstallPrevious
  - Architecture: x64
    NestedInstallerType: portable
    NestedInstallerFiles:
      - RelativeFilePath: gitcd.exe
        PortableCommandAlias: gitcd
    InstallerUrl: ${base_url}/gitcd_windows_amd64.zip
    InstallerSha256: ${sha_amd64}
    UpgradeBehavior: uninstallPrevious
ManifestType: installer
ManifestVersion: 1.28.0
Dependencies:
  PackageDependencies:
    - PackageIdentifier: Git.Git
EOF
)"

nl=$'\n'

# s text old new replaces the first occurrence of old, sa every occurrence.
# The pattern and the replacement come through variables, which every bash
# the repository runs on expands the same way.
s() {
  local text="$1" old="$2" new="$3"
  printf '%s' "${text/$old/$new}"
}
sa() {
  local text="$1" old="$2" new="$3"
  printf '%s' "${text//$old/$new}"
}

# write_set writes the three files and the checksums file, each from the
# variable of the same name, so a case overrides only what it changes.
write_set() {
  rm -rf "${manifest}"
  mkdir -p "${manifest}"
  printf '%s\n' "${v_version}" >"${manifest}/${id}.yaml"
  printf '%s\n' "${v_installer}" >"${manifest}/${id}.installer.yaml"
  printf '%s\n' "${v_locale}" >"${manifest}/${id}.locale.en-US.yaml"
  printf '%s\n' "${v_checksums}" >"${checksums}"
}

reset_vars() {
  v_version="${version_base}"
  v_installer="${installer_base}"
  v_locale="${locale_base}"
  v_checksums="${checksums_base}"
}

# report name want [tag] [version] checks the set already on disk.
report() {
  local name="$1" want="$2" check_tag="${3:-${tag}}" status=0
  if [ -n "${4:-}" ]; then
    "${validator}" "${manifest}" "${check_tag}" "${checksums}" "$4" >/dev/null 2>"${work}/stderr" || status=$?
  else
    "${validator}" "${manifest}" "${check_tag}" "${checksums}" >/dev/null 2>"${work}/stderr" || status=$?
  fi
  if [ "${want}" = "accept" ] && [ "${status}" -ne 0 ]; then
    echo "FAIL ${name}: rejected, want accepted: $(cat "${work}/stderr")"
    failures=$((failures + 1))
    return
  fi
  if [ "${want}" = "reject" ] && [ "${status}" -eq 0 ]; then
    echo "FAIL ${name}: accepted, want rejected"
    failures=$((failures + 1))
    return
  fi
  echo "PASS ${name}"
}

# accept and reject take the case name and, optionally, a tag and a version
# for the validator. The variables v_version, v_installer, v_locale and
# v_checksums hold the set, a case changes them first.
accept() {
  write_set
  report "$1" accept "${2:-${tag}}" "${3:-}"
  reset_vars
}
reject() {
  write_set
  report "$1" reject "${2:-${tag}}" "${3:-}"
  reset_vars
}

# reject_with name text rejects like reject and also needs the validator's
# message to contain text. Several rules overlap, the skeleton comparison at
# the end rejects most altered files on its own, so a rule that stops working
# would go unseen when only the exit status is read. These cases break exactly
# one rule and name the message of that rule.
reject_with() {
  local name="$1" want="$2"
  write_set
  report "${name}" reject "${tag}" ""
  if ! grep -qF -- "${want}" "${work}/stderr"; then
    echo "FAIL ${name}: stderr = $(cat "${work}/stderr"), want it to contain $(printf '%q' "${want}")"
    failures=$((failures + 1))
  fi
  reset_vars
}

reset_vars

arm_url="    InstallerUrl: ${base_url}/gitcd_windows_arm64.zip"
amd_url="    InstallerUrl: ${base_url}/gitcd_windows_amd64.zip"
arm_sha="    InstallerSha256: ${sha_arm64}"
amd_sha="    InstallerSha256: ${sha_amd64}"
dep='    - PackageIdentifier: Git.Git'

accept "the generated manifests are accepted"
accept "a version passed explicitly, as a snapshot check does" "${tag}" "1.0.0"
reject "a version passed that the files do not carry" "${tag}" "1.0.1"

# Shape of the set.
rm -rf "${manifest}"
write_set
rm "${manifest}/${id}.installer.yaml"
report "a missing installer file" reject
write_set
rm "${manifest}/${id}.locale.en-US.yaml"
report "a missing locale file" reject
write_set
rm "${manifest}/${id}.yaml"
report "a missing version file" reject
write_set
: >"${manifest}/${id}.yaml"
report "an empty version file" reject
write_set
echo extra >"${manifest}/${id}.locale.de-DE.yaml"
report "an extra locale file" reject
write_set
mkdir "${manifest}/sub"
report "an extra directory" reject
reset_vars
write_set
report "a version that is not a version" reject "${tag}" "latest"
write_set
: >"${checksums}"
report "an empty checksums file" reject

# Values the template pins.
v_version="$(s "${version_base}" "OstendorfCloud.gitcd" "Other.gitcd")"
reject "another package identifier in the version file"
v_locale="$(s "${locale_base}" "Publisher: Ostendorf Cloud" "Publisher: Someone Else")"
reject "another publisher"
v_locale="$(s "${locale_base}" "Moniker: gitcd" "Moniker: other")"
reject "another moniker"
v_locale="$(s "${locale_base}" "Moniker: gitcd${nl}" "")"
reject "no moniker"
v_locale="$(s "${locale_base}" "License: Apache-2.0" "License: MIT")"
reject "another license"
v_locale="$(s "${locale_base}" "  - cli" "  - cli${nl}  - extra")"
reject "an extra tag"
v_version="$(s "${version_base}" "1.28.0" "1.10.0")"
reject "another manifest version in the version file"
v_installer="$(s "${installer_base}" "InstallerType: zip" "InstallerType: exe")"
reject "another installer type"
v_installer="$(s "${installer_base}" "NestedInstallerType: portable" "NestedInstallerType: exe")"
reject "another nested installer type"
v_installer="$(s "${installer_base}" "RelativeFilePath: gitcd.exe" "RelativeFilePath: evil.exe")"
reject "another nested file"
v_installer="$(s "${installer_base}" "${dep}" "${dep}${nl}    - PackageIdentifier: Evil.Package")"
reject "an extra dependency"
v_installer="$(s "${installer_base}" "Dependencies:${nl}  PackageDependencies:${nl}${dep}" "")"
reject "no git dependency"
v_installer="$(s "${installer_base}" "InstallerLocale: en-US" "InstallerLocale: en-US${nl}InstallerSwitches:${nl}  Silent: --evil")"
reject "installer switches"
v_installer="$(s "${installer_base}" "    UpgradeBehavior: uninstallPrevious" "    UpgradeBehavior: install")"
reject "another upgrade behavior"
v_installer="$(s "${installer_base}" 'ReleaseDate: "2026-11-16"' 'ReleaseDate: yesterday')"
reject "a release date that is not a date"
v_installer="$(s "${installer_base}" 'ReleaseDate: "2026-11-16"' "")"
reject "no release date"

# The version.
v_version="$(s "${version_base}" "PackageVersion: 1.0.0" "PackageVersion: 1.0.1")"
reject "another version in the version file"
v_locale="$(s "${locale_base}" "PackageVersion: 1.0.0" "PackageVersion: 1.0.1")"
reject "another version in the locale file"
v_installer="$(s "${installer_base}" "PackageVersion: 1.0.0" "PackageVersion: 1.0.1")"
reject "another version in the installer file"
v_installer="$(s "${installer_base}" "PackageVersion: 1.0.0" "PackageVersion: 1.0.0${nl}PackageVersion: 1.0.0")"
reject "a repeated version line"
write_set
report "the manifests checked for another tag" reject "v1.0.1"

# URLs: host, tag, shape.
v_installer="$(s "${installer_base}" "${arm_url}" "$(s "${arm_url}" github.com example.invalid)")"
reject "another host"
v_installer="$(s "${installer_base}" "${arm_url}" "$(s "${arm_url}" "https://" "https://ostendorf-cloud@")")"
reject "userinfo in the url"
v_installer="$(s "${installer_base}" "${arm_url}" "${arm_url}?x=1")"
reject "a query string in the url"
v_installer="$(s "${installer_base}" "${arm_url}" "$(s "${arm_url}" v1.0.0 v1.0.1)")"
reject "another tag in a url"
v_installer="$(s "${installer_base}" "${arm_url}" "$(s "${arm_url}" v1.0.0 v1x0x0)")"
reject "a tag whose dots are not literal"
v_installer="$(s "${installer_base}" "${arm_url}" "$(s "${arm_url}" gitcd_windows_arm64.zip gitcd_linux_arm64.tar.gz)")"
reject "a url that is not a Windows archive"
v_installer="$(s "${installer_base}" "${arm_url}" "$(s "${arm_url}" ostendorf-cloud/gitcd other/gitcd)")"
reject "another repository"
v_installer="$(s "${installer_base}" "${arm_url}" "${amd_url}")"
reject "the amd64 url twice and no arm64 url"
v_installer="$(s "${installer_base}" "${arm_url}${nl}${arm_sha}" "${amd_url}${nl}${amd_sha}")"
reject "the amd64 archive under the arm64 architecture"
v_installer="$(s "${installer_base}" "${arm_url}${nl}${arm_sha}" "${amd_url}${nl}${arm_sha}")"
reject "the amd64 url with the arm64 sha256"
v_installer="$(s "${installer_base}" "${arm_url}" "${arm_url}${nl}${arm_url}")"
reject "a url repeated"

# One rule each: the architecture label, the url and the order of the blocks.
v_installer="$(s "$(s "$(s "${installer_base}" "Architecture: arm64" "Architecture: @@")" "Architecture: x64" "Architecture: arm64")" "Architecture: @@" "Architecture: x64")"
reject_with "the architecture labels swapped, urls and shas in place" "archive under the"
v_installer="$(s "${installer_base}" "${arm_url}" "$(s "${arm_url}" github.com example.invalid)")"
reject_with "a foreign url under the right architecture" "the arm64 entry of the installer file: an InstallerUrl that is not this repository's release download"
inst_pre="${installer_base%%  - Architecture: arm64*}"
inst_rest="${installer_base#*  - Architecture: arm64}"
inst_arm_body="${inst_rest%%  - Architecture: x64*}"
inst_rest2="${inst_rest#*  - Architecture: x64}"
inst_x64_body="${inst_rest2%%ManifestType: installer*}"
inst_post="ManifestType: installer${inst_rest2#*ManifestType: installer}"
v_installer="${inst_pre}  - Architecture: x64${inst_x64_body}  - Architecture: arm64${inst_arm_body}${inst_post}"
accept "the x64 entry before the arm64 entry, each url under its own architecture"
v_installer="${inst_pre}  - Architecture: x64${inst_x64_body}  - Architecture: arm64${inst_arm_body}${inst_post}"
v_installer="$(s "${v_installer}" "${amd_sha}" "    InstallerSha256: ${sha_other}")"
reject_with "the x64 entry first with a sha256 that differs from the checksums file" "differs from the checksums file"
v_installer="${inst_pre}  - Architecture: x64${inst_x64_body}  - Architecture: arm64${inst_arm_body}${inst_post}"
v_installer="$(s "${v_installer}" "${amd_url}" "$(s "${amd_url}" github.com example.invalid)")"
reject_with "the x64 entry first with a foreign url, named by its entry" "the x64 entry of the installer file: an InstallerUrl that is not this repository's release download"
v_installer="${inst_pre}  - Architecture: x64${inst_x64_body}  - Architecture: arm64${inst_arm_body}${inst_post}"
v_installer="$(s "${v_installer}" "Architecture: x64" "Architecture: @@")"
v_installer="$(s "${v_installer}" "Architecture: arm64" "Architecture: x64")"
v_installer="$(s "${v_installer}" "Architecture: @@" "Architecture: arm64")"
reject_with "the architecture labels swapped with the entries in the other order" "archive under the"
v_installer="$(s "${installer_base}" "  - Architecture: arm64" "  - Architecture: x64")"
reject_with "two x64 entries and no arm64 entry" "once each, has 0 and 2"
v_installer="$(s "${installer_base}" "${amd_sha}" "${amd_sha}${nl}${amd_url}${nl}${amd_sha}")"
reject_with "the url and sha256 of one entry twice" "must list the arm64 archive and the amd64 archive once each"
v_installer="$(s "${installer_base}" "  - Architecture: x64" "  - Architecture: arm64")"
reject_with "two arm64 entries and no x64 entry" "once each, has 2 and 0"

# sha256 lines.
v_installer="$(s "${installer_base}" "${arm_sha}${nl}" "")"
reject "a url without its sha256"
v_installer="$(s "${installer_base}" "${arm_sha}" "    InstallerSha256: ${sha_other}")"
reject "a sha256 that differs from the checksums file"
v_installer="$(s "${installer_base}" "${arm_sha}" "    InstallerSha256: ABC")"
reject "a sha256 that is not 64 lower case hex digits"
v_installer="$(s "${installer_base}" "${arm_sha}" "${arm_sha}${nl}${arm_sha}")"
reject "an extra sha256 line"
v_checksums="$(s "${checksums_base}" "${sha_arm64}  gitcd_windows_arm64.zip" "")"
reject "no checksums entry for an archive"
v_checksums="${checksums_base}${nl}${sha_other}  gitcd_windows_arm64.zip"
reject "two checksums entries for an archive"
v_checksums="$(s "${checksums_base}" "${sha_arm64}  gitcd_windows_arm64.zip" "${sha_arm64}  xgitcd_windows_arm64.zip")"
reject "a checksums entry for another file name"

# Code or characters hidden in a line the template has.
v_locale="$(s "${locale_base}" "Moniker: gitcd" "Moniker: gitcd # x")"
reject "a comment on a line"
v_locale="$(s "${locale_base}" "PackageName: gitcd" "PackageName: gitcd ")"
reject "a trailing space"
v_locale="$(sa "${locale_base}" "${nl}" $'\r\n')"
reject "a carriage return at the end of every line"
v_locale="$(s "${locale_base}" "PackageName: gitcd" $'PackageName:\tgitcd')"
reject "a tab in a line"
v_locale="$(s "${locale_base}" "PackageName: gitcd" $'PackageName: g\xd1\x96tcd')"
reject "a Cyrillic look-alike"
v_locale="$(s "${locale_base}" "PackageName: gitcd" "PackageName: gitcd"$'\x04')"
reject "an end of transmission byte"
v_locale="${locale_base}${nl}${nl}"
reject "a blank line after the last line"
v_locale="${locale_base}${nl}Extra: x"
reject "an extra key after the last line"
v_locale="$(s "${locale_base}" "ManifestType: defaultLocale" "ManifestType: defaultLocale${nl}ManifestType: defaultLocale")"
reject "a repeated key"

write_set
printf '\xef\xbb\xbf%s\n' "${locale_base}" >"${manifest}/${id}.locale.en-US.yaml"
report "a byte order mark" reject

write_set
printf '%s\n\0' "${locale_base}" >"${manifest}/${id}.locale.en-US.yaml"
report "a NUL byte after the last line" reject

write_set
{
  printf '%s\n' "${locale_base%ManifestVersion: 1.28.0}"
  printf 'ManifestVersion: 1.28.0\0Extra: x\n'
} >"${manifest}/${id}.locale.en-US.yaml"
report "a NUL byte hiding a key at the end of a line" reject

write_set
printf '%s' "${locale_base}" >"${manifest}/${id}.locale.en-US.yaml"
report "a final line without a newline" reject

# The installer file has no skeleton diff of its own that sees a missing final
# newline, since its entries are rebuilt with one, so the newline rule alone
# decides here.
write_set
printf '%s' "${installer_base}" >"${manifest}/${id}.installer.yaml"
report "an installer file without a final newline" reject
if ! grep -qF "does not end with a newline" "${work}/stderr"; then
  echo "FAIL an installer file without a final newline: stderr = $(cat "${work}/stderr"), want the newline rule"
  failures=$((failures + 1))
fi

if [ "${failures}" -ne 0 ]; then
  finished=yes
  echo "${failures} test(s) failed"
  exit 1
fi

finished=yes
echo "all tests passed"
