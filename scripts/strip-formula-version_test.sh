# Table driven tests for strip-formula-version.sh: formulas that must lose
# exactly their version line, and altered ones that must be rejected with the
# file left byte for byte as it was.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
strip="${script_dir}/strip-formula-version.sh"
# An explicit template, because macOS mktemp ignores TMPDIR without one.
work="$(mktemp -d "${TMPDIR:-/tmp}/strip-formula-version-test.XXXXXXXX")"
finished=no
# An old bash can stop a script on an expansion it does not know and still
# exit 0, so a run that did not reach its last line fails here.
trap 'rm -rf "${work}"; if [ "${finished}" != yes ]; then if [ "${failures:-0}" -eq 0 ]; then echo "test script stopped before its last line" >&2; fi; exit 1; fi' EXIT

failures=0
dir="${work}/case"
file="${dir}/gitcd.rb"

base_url="https://github.com/acme/widget/releases/download/v1.2.3"
version='  version "1.2.3"'
nl=$'\n'

base="$(
  cat <<EOF
# typed: false
# frozen_string_literal: true

# This file was generated by GoReleaser. DO NOT EDIT.
class Widget < Formula
  desc "Do a thing with a version 1.2.3 per remote"
  homepage "https://github.com/acme/widget"
${version}
  license "Apache-2.0"

  depends_on "git"

  on_macos do
    if Hardware::CPU.intel?
      url "${base_url}/widget_darwin_amd64.tar.gz"
      sha256 "1111111111111111111111111111111111111111111111111111111111111111"
    end
    if Hardware::CPU.arm?
      url "${base_url}/widget_darwin_arm64.tar.gz"
      sha256 "2222222222222222222222222222222222222222222222222222222222222222"
    end
  end

  on_linux do
    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?
      url "${base_url}/widget_linux_amd64.tar.gz"
      sha256 "3333333333333333333333333333333333333333333333333333333333333333"
    end
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/widget version")
  end
end
EOF
)"

s() {
  local text="$1" old="$2" new="$3"
  printf '%s' "${text/$old/$new}"
}
sa() {
  local text="$1" old="$2" new="$3"
  printf '%s' "${text//$old/$new}"
}

# prepare body writes the body plus a trailing newline into a fresh case
# directory, mode 0640 so a kept mode is visible.
prepare() {
  rm -rf "${dir}"
  mkdir -p "${dir}"
  printf '%s\n' "$1" >"${file}"
  chmod 640 "${file}"
}

mode_of() {
  # The mode in octal digits, 640 when the file kept the mode prepare gave it.
  if [ -n "$(find "$1" -maxdepth 0 -perm 640)" ]; then
    echo 640
  else
    echo changed
  fi
}

# finish name want status: a rejected file is unchanged and leaves nothing
# else in its directory, an accepted one is the expectation.
accept() {
  local name="$1" body="$2" expected="$3" status=0
  prepare "${body}"
  cp "${file}" "${work}/before"
  "${strip}" "${file}" >/dev/null 2>"${work}/stderr" || status=$?
  if [ "${status}" -ne 0 ]; then
    echo "FAIL ${name}: rejected, want accepted: $(cat "${work}/stderr")"
    failures=$((failures + 1))
    return
  fi
  printf '%s\n' "${expected}" >"${work}/expected"
  if ! cmp -s "${work}/expected" "${file}"; then
    echo "FAIL ${name}: the result is not the expected formula"
    failures=$((failures + 1))
    return
  fi
  if [ "$(find "${dir}" -mindepth 1 | wc -l | tr -d ' ')" -ne 1 ]; then
    echo "FAIL ${name}: a temporary file is left behind"
    failures=$((failures + 1))
    return
  fi
  if [ "$(mode_of "${file}")" != 640 ]; then
    echo "FAIL ${name}: the file mode changed from 640"
    failures=$((failures + 1))
    return
  fi
  echo "PASS ${name}"
}

reject() {
  local name="$1" body="$2" want_message="${3:-}" status=0
  prepare "${body}"
  cp "${file}" "${work}/before"
  "${strip}" "${file}" >/dev/null 2>"${work}/stderr" || status=$?
  check_rejected "${name}" "${status}" "${want_message}"
}

# check_rejected name status message checks a run on ${file}.
check_rejected() {
  local name="$1" status="$2" want_message="$3"
  if [ "${status}" -eq 0 ]; then
    echo "FAIL ${name}: accepted, want rejected"
    failures=$((failures + 1))
    return
  fi
  if ! cmp -s "${work}/before" "${file}"; then
    echo "FAIL ${name}: the file changed although it was rejected"
    failures=$((failures + 1))
    return
  fi
  if [ "$(find "${dir}" -mindepth 1 | wc -l | tr -d ' ')" -ne 1 ]; then
    echo "FAIL ${name}: a temporary file is left behind"
    failures=$((failures + 1))
    return
  fi
  if [ -n "${want_message}" ] && ! grep -qF -- "${want_message}" "${work}/stderr"; then
    echo "FAIL ${name}: stderr does not say '${want_message}': $(cat "${work}/stderr")"
    failures=$((failures + 1))
    return
  fi
  echo "PASS ${name}"
}

without_version="$(s "${base}" "${version}${nl}" "")"

accept "the version line is removed and nothing else" "${base}" "${without_version}"
accept "a snapshot version with the urls of its tag" \
  "$(s "${base}" "${version}" '  version "1.2.3-SNAPSHOT-e1a14bc"')" "${without_version}"

# The version word elsewhere is not the line to remove.
accept "the word version inside desc and the test block stays" "${base}" "${without_version}"
reject "no version line" "${without_version}" "no line of the form"
reject "two version lines" "$(s "${base}" "${version}" "${version}${nl}${version}")" "found 2"
reject "a second version line with another indent" \
  "$(s "${base}" "  license" "    version \"1.2.3\"${nl}  license")" "found 2 lines starting with the word version"
reject "the only version line indented by four spaces" \
  "$(s "${base}" "${version}" '    version "1.2.3"')" "no line of the form"
reject "the only version line indented by a tab" \
  "$(s "${base}" "${version}" $'\tversion "1.2.3"')" "no line of the form"
reject "a version line with a trailing space" \
  "$(s "${base}" "${version}" "${version} ")" "no line of the form"
reject "an empty version" "$(s "${base}" "${version}" '  version ""')" "no line of the form"
reject "a version line with a trailing comment" \
  "$(s "${base}" "${version}" "${version} # x")" "no line of the form"

# The urls must carry the same version.
reject "the version differs from the urls" "$(s "${base}" "${version}" '  version "1.2.4"')" "not the version 1.2.3"
reject "a snapshot suffix of another version" \
  "$(s "${base}" "${version}" '  version "1.2.4-SNAPSHOT-abc"')" "not the version 1.2.3"
reject "a snapshot suffix that is not hex" \
  "$(s "${base}" "${version}" '  version "1.2.3-SNAPSHOT-xyz"')" "not the version 1.2.3"
reject "a release candidate suffix" \
  "$(s "${base}" "${version}" '  version "1.2.3-rc.1"')" "not the version 1.2.3"
reject "one url with another tag" \
  "$(s "${base}" "${base_url}/widget_linux_amd64" "https://github.com/acme/widget/releases/download/v1.2.4/widget_linux_amd64")" \
  "different versions"
reject "a url without the version" \
  "$(s "${base}" "${base_url}/widget_linux_amd64.tar.gz" "https://github.com/acme/widget/releases/latest/download/widget_linux_amd64.tar.gz")" \
  "not a plain GitHub release download"
reject "a url on another host" \
  "$(s "${base}" "github.com/acme/widget/releases" "example.invalid/acme/widget/releases")" "not a plain GitHub release download"
reject "a url without the v before the version" \
  "$(sa "${base}" "download/v1.2.3" "download/1.2.3")" "not a plain GitHub release download"
reject "a url with a two part version" \
  "$(sa "$(s "${base}" "${version}" '  version "1.2"')" "download/v1.2.3" "download/v1.2")" "not a plain GitHub release download"
reject "a url with a pre-release tag" \
  "$(sa "$(s "${base}" "${version}" '  version "1.2.3-rc.1"')" "download/v1.2.3" "download/v1.2.3-rc.1")" "not a plain GitHub release download"
reject "a url with a query string" \
  "$(s "${base}" "widget_linux_amd64.tar.gz" "widget_linux_amd64.tar.gz?x=1")" "not a plain GitHub release download"
reject "a url with a hyphenated archive name" \
  "$(s "${base}" "widget_linux_amd64" "widget-2020-01-01")" "not a plain GitHub release download"
reject "a url with a trailing space" \
  "$(s "${base}" "widget_linux_amd64.tar.gz\"" "widget_linux_amd64.tar.gz\" ")" "not a plain GitHub release download"
reject "a url indented by another width" \
  "$(s "${base}" "      url \"${base_url}/widget_linux_amd64" "    url \"${base_url}/widget_linux_amd64")" "not a plain GitHub release download"
reject "no url line at all" \
  "$(printf '%s\n' "${base}" | grep -v -E '^[[:space:]]*url ')" "no url line"

# Bytes that hide from a line reader.
reject "a carriage return at the end of every line" "$(sa "${base}" "${nl}" $'\r\n')" "carriage return"
reject "a lone carriage return in the version line" \
  "$(s "${base}" "${version}" "${version}"$'\r')" "carriage return"

prepare "${base}"
printf '\0' >>"${file}"
cp "${file}" "${work}/before"
status=0
"${strip}" "${file}" >/dev/null 2>"${work}/stderr" || status=$?
check_rejected "a NUL byte after the formula" "${status}" "NUL byte"

# Files that are not a formula.
rm -rf "${dir}"
mkdir -p "${dir}"
: >"${file}"
cp "${file}" "${work}/before"
status=0
"${strip}" "${file}" >/dev/null 2>"${work}/stderr" || status=$?
check_rejected "an empty file" "${status}" "empty"

rm -rf "${dir}"
mkdir -p "${dir}"
: >"${work}/before"
status=0
"${strip}" "${dir}/missing.rb" >/dev/null 2>"${work}/stderr" || status=$?
if [ "${status}" -eq 0 ] || ! grep -qF "no such file" "${work}/stderr" || [ -e "${dir}/missing.rb" ] ||
  [ "$(find "${dir}" -mindepth 1 | wc -l | tr -d ' ')" -ne 0 ]; then
  echo "FAIL a missing file is not reported and left alone"
  failures=$((failures + 1))
else
  echo "PASS a missing file is reported and nothing is created"
fi

status=0
"${strip}" >/dev/null 2>&1 || status=$?
if [ "${status}" -ne 2 ]; then
  echo "FAIL no argument exits ${status}, want 2"
  failures=$((failures + 1))
else
  echo "PASS no argument is a usage error"
fi

# The word version without the line shape stays when another line is removed:
# the removed line is the only one that changes.
prepare "${base}"
"${strip}" "${file}"
if ! grep -qF 'desc "Do a thing with a version 1.2.3 per remote"' "${file}" ||
  ! grep -qF 'assert_match version.to_s' "${file}"; then
  echo "FAIL the version word in desc or the test block was touched"
  failures=$((failures + 1))
else
  echo "PASS the version word in desc and the test block is untouched"
fi

if [ "${failures}" -ne 0 ]; then
  finished=yes
  echo "${failures} test(s) failed"
  exit 1
fi

finished=yes
echo "all tests passed"
