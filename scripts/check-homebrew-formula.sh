# Usage: check-homebrew-formula.sh <formula file> <tag>
#
# Verifies the formula against the shape goreleaser generates from
# .goreleaser.yaml: every line must match one of the line shapes below, so
# nothing but the generated template passes. The URLs must be this
# repository's own release downloads for <tag>, one per known platform, each
# followed by a 64 digit hex sha256.
#
# The formula carries no version line: goreleaser writes one, and
# strip-formula-version.sh removes it before this check runs, since
# Homebrew's audit flags it as redundant with the version in the URLs. A
# formula that still has one is rejected.
#
# The shapes come from a snapshot build (task test:formula runs this script
# on one), so a change to the brews entry that alters the generated lines
# fails there first and this list is updated with it.
set -euo pipefail

if [ "$#" -ne 2 ]; then
  echo "usage: $0 <formula file> <tag>" >&2
  exit 2
fi

formula="$1"
tag="$2"

if [ ! -s "${formula}" ]; then
  echo "formula ${formula} is missing or empty" >&2
  exit 1
fi

# Defence in depth, behind the line allowlist below: the bash this runs on
# may drop a NUL byte on read (3.2 does) or cut the line at it, so the file
# is compared with a copy that has none.
size="$(wc -c <"${formula}" | tr -d ' ')"
without_nul="$(tr -d '\0' <"${formula}" | wc -c | tr -d ' ')"
if [ "${size}" != "${without_nul}" ]; then
  echo "formula contains a NUL byte" >&2
  exit 1
fi

# Also defence in depth behind the line allowlist, which rejects these lines
# on its own. Printable ASCII and newlines only: a tab, a carriage return, a control
# character, a byte order mark or any non-ASCII look-alike is refused before
# the line shapes are compared.
if LC_ALL=C grep -q -v -E '^[[:print:]]*$' "${formula}"; then
  echo "formula contains a character outside printable ASCII" >&2
  exit 1
fi

tag_re="${tag//./\\.}"
tag_re="${tag_re//+/\\+}"
download="https://github.com/ostendorf-cloud/gitcd/releases/download/${tag_re}"

# Fixed lines, compared as a whole.
fixed=(
  '# typed: false'
  '# frozen_string_literal: true'
  ''
  '# This file was generated by GoReleaser. DO NOT EDIT.'
  'class Gitcd < Formula'
  '  desc "Clone repositories into a predictable layout and set a git identity per remote"'
  '  homepage "https://github.com/ostendorf-cloud/gitcd"'
  '  license "Apache-2.0"'
  '  depends_on "git"'
  '    if Hardware::CPU.intel?'
  '    if Hardware::CPU.arm?'
  '    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?'
  '    if Hardware::CPU.arm? && Hardware::CPU.is_64_bit?'
  '      define_method(:install) do'
  '        bin.install "gitcd"'
  '      end'
  '    end'
  '  end'
  '  test do'
  '    assert_match version.to_s, shell_output("#{bin}/gitcd version")'
  'end'
)

version_line_re='^[[:space:]]*version[[:space:]]'
url_re="^      url \"${download}/gitcd_(darwin|linux)_(amd64|arm64)\\.tar\\.gz\"\$"
sha_re='^      sha256 "[0-9a-f]{64}"$'

section=""
guard=""
want_sha=0
urls=""
line_no=0

fail() {
  echo "formula line ${line_no} is not part of the generated formula: ${1}" >&2
  exit 1
}

while IFS= read -r line || [ -n "${line}" ]; do
  line_no=$((line_no + 1))

  if [ "${want_sha}" -eq 1 ]; then
    if ! [[ ${line} =~ ${sha_re} ]]; then
      fail "a url must be followed by its sha256"
    fi
    want_sha=0
    continue
  fi

  case "${line}" in
  '  on_macos do')
    section="darwin"
    continue
    ;;
  '  on_linux do')
    section="linux"
    continue
    ;;
  '    if Hardware::CPU.intel?'*) guard="amd64" ;;
  '    if Hardware::CPU.arm?'*) guard="arm64" ;;
  esac

  if [[ ${line} =~ ${version_line_re} ]]; then
    fail "the version line must be gone, strip-formula-version.sh removes it and Homebrew scans the version from the urls"
  fi

  if [[ ${line} =~ ${url_re} ]]; then
    os="${BASH_REMATCH[1]}"
    arch="${BASH_REMATCH[2]}"
    if [ "${os}" != "${section}" ]; then
      fail "a ${os} url outside its on_${section:-none} block"
    fi
    # The guard above names the CPU: intel gets amd64, arm gets arm64.
    if [ "${arch}" != "${guard}" ]; then
      fail "a ${arch} url under the ${guard:-no} CPU guard"
    fi
    urls="${urls}${os}_${arch}"$'\n'
    want_sha=1
    continue
  fi

  matched=0
  for shape in "${fixed[@]}"; do
    if [ "${line}" = "${shape}" ]; then
      matched=1
      break
    fi
  done
  if [ "${matched}" -eq 0 ]; then
    fail "${line}"
  fi
done <"${formula}"

if [ "${want_sha}" -eq 1 ]; then
  echo "formula ends after a url without its sha256" >&2
  exit 1
fi

# Each of these lines appears exactly once, which keeps a second class, a
# second block or a second description out. These checks say what is wrong in
# plain words. The order of the lines is pinned by the skeleton comparison at
# the end, since Ruby ignores indentation and a reordering of allowed lines
# can change what the formula does.
once=(
  '# typed: false'
  '# frozen_string_literal: true'
  '# This file was generated by GoReleaser. DO NOT EDIT.'
  'class Gitcd < Formula'
  '  homepage "https://github.com/ostendorf-cloud/gitcd"'
  '  license "Apache-2.0"'
  '  depends_on "git"'
  '  on_macos do'
  '  on_linux do'
  '  test do'
  'end'
)
for shape in "${once[@]}"; do
  count="$(grep -cxF -- "${shape}" "${formula}" || true)"
  if [ "${count}" -ne 1 ]; then
    echo "formula must carry the line '${shape}' exactly once, has ${count}" >&2
    exit 1
  fi
done
desc_count="$(grep -c '^  desc ' "${formula}" || true)"
if [ "${desc_count}" -ne 1 ]; then
  echo "formula must carry exactly one desc line, has ${desc_count}" >&2
  exit 1
fi
if [ "$(tail -n 1 "${formula}")" != "end" ]; then
  echo "formula must end with the class's end line" >&2
  exit 1
fi
for platform in darwin_amd64 darwin_arm64 linux_amd64 linux_arm64; do
  count="$(printf '%s' "${urls}" | grep -cx "${platform}" || true)"
  if [ "${count}" -ne 1 ]; then
    echo "formula must carry exactly one url for ${platform}, has ${count}" >&2
    exit 1
  fi
done

# The platforms in file order, as the snapshot formula lists them: the
# skeleton comparison cannot see which archive sits under which guard.
expected_urls=$'darwin_amd64\ndarwin_arm64\nlinux_amd64\nlinux_arm64\n'
if [ "${urls}" != "${expected_urls}" ]; then
  echo "formula urls must be darwin_amd64, darwin_arm64, linux_amd64, linux_arm64 in this order" >&2
  exit 1
fi

# The whole file against the skeleton of the generated formula: every url,
# and sha256 value replaced by a placeholder, everything else, the
# order and the indentation included, as goreleaser writes it. Ruby ignores
# indentation, so a reordering of allowed lines (dropping the CPU guards,
# moving a line into another block) passes every check above and changes what
# the formula does. "task test:formula" runs this on a snapshot build, so a
# change to the brews entry has to update the skeleton below.
compare_dir="$(mktemp -d "${TMPDIR:-/tmp}/check-homebrew-formula.XXXXXXXX")"
trap 'rm -rf "${compare_dir}"' EXIT
sed -E \
  -e 's|^(      url ")[^"]*(")$|\1URL\2|' \
  -e 's|^(      sha256 ")[^"]*(")$|\1SHA256\2|' \
  "${formula}" >"${compare_dir}/formula"
cat >"${compare_dir}/skeleton" <<'SKELETON'
# typed: false
# frozen_string_literal: true

# This file was generated by GoReleaser. DO NOT EDIT.
class Gitcd < Formula
  desc "Clone repositories into a predictable layout and set a git identity per remote"
  homepage "https://github.com/ostendorf-cloud/gitcd"
  license "Apache-2.0"

  depends_on "git"

  on_macos do
    if Hardware::CPU.intel?
      url "URL"
      sha256 "SHA256"

      define_method(:install) do
        bin.install "gitcd"
      end
    end
    if Hardware::CPU.arm?
      url "URL"
      sha256 "SHA256"

      define_method(:install) do
        bin.install "gitcd"
      end
    end
  end

  on_linux do
    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?
      url "URL"
      sha256 "SHA256"
      define_method(:install) do
        bin.install "gitcd"
      end
    end
    if Hardware::CPU.arm? && Hardware::CPU.is_64_bit?
      url "URL"
      sha256 "SHA256"
      define_method(:install) do
        bin.install "gitcd"
      end
    end
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/gitcd version")
  end
end
SKELETON
if ! diff "${compare_dir}/skeleton" "${compare_dir}/formula" >&2; then
  echo "formula differs from the generated skeleton (lines starting with > are in the formula)" >&2
  exit 1
fi
