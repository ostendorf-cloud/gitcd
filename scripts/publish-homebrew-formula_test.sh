# Unit tests for publish-homebrew-formula.sh and, through it,
# check-homebrew-formula.sh. A fake gh stands in for the GitHub CLI, logging
# every call with the token it ran under, so these run offline and never
# touch a real release or tap. The tokens are dummy strings, never real
# credentials.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
script="${script_dir}/publish-homebrew-formula.sh"
# An explicit template, because macOS mktemp ignores TMPDIR without one.
work="$(mktemp -d "${TMPDIR:-/tmp}/publish-homebrew-formula-test.XXXXXXXX")"
finished=no
# An old bash can stop a script on an expansion it does not know and still
# exit 0, so a run that did not reach its last line fails here.
trap 'rm -rf "${work}"; if [ "${finished}" != yes ]; then echo "test script stopped before its last line" >&2; exit 1; fi' EXIT

fake_bin="${work}/fake-bin"
mkdir -p "${fake_bin}"

# The fake gh is steered by environment variables, one per behaviour:
#   FAKE_DRAFT          false (default), true (a draft the token can see) or
#                       hidden (what a read-only token gets for a draft: 404)
#   FAKE_PRERELEASE     the isPrerelease answer (default false)
#   FAKE_VIEW_FAILS     set: "release view" fails
#   FAKE_DOWNLOAD_FAILS set: "release download" fails
#   FAKE_FORMULA        the formula body the release asset holds
#   FAKE_CHECKSUMS      the checksums file the release holds
#   FAKE_TAP_STATE      missing (404), present, error (HTTP 502)
#   FAKE_TAP_FILE       the content the tap holds when present
#   FAKE_PUT_FAILS      set: the contents PUT fails
# Every call is logged as "<token> gh <args>", the content of a PUT is
# written to put-content instead of the log.
cat <<'FAKE_GH' >"${fake_bin}/gh"
#!/usr/bin/env bash
args=()
for a in "$@"; do
  case "${a}" in
  content=*)
    printf '%s' "${a#content=}" >"${CASE_DIR}/put-content"
    args+=("content=<base64>")
    ;;
  *) args+=("${a}") ;;
  esac
done
echo "${GH_TOKEN:-none} gh ${args[*]}" >>"${CALL_LOG}"

case "$1 $2" in
"release view")
  if [ -n "${FAKE_VIEW_FAILS:-}" ]; then
    echo "fake gh: release view failed" >&2
    exit 1
  fi
  if [ "${FAKE_DRAFT:-false}" = "hidden" ]; then
    echo "fake gh: release not found (HTTP 404)" >&2
    exit 1
  fi
  echo "${FAKE_DRAFT:-false} ${FAKE_PRERELEASE:-false}"
  exit 0
  ;;
"release download")
  if [ -n "${FAKE_DOWNLOAD_FAILS:-}" ]; then
    echo "fake gh: download failed" >&2
    exit 1
  fi
  dir=""
  pattern=""
  for ((i = 1; i <= $#; i++)); do
    j=$((i + 1))
    case "${!i}" in
    --dir) dir="${!j}" ;;
    --pattern) pattern="${!j}" ;;
    esac
  done
  case "${pattern}" in
  gitcd.rb) printf '%s\n' "${FAKE_FORMULA}" >"${dir}/gitcd.rb" ;;
  *_checksums.txt) printf '%s\n' "${FAKE_CHECKSUMS}" >"${dir}/gitcd_1.0.0_checksums.txt" ;;
  *)
    echo "fake gh: unknown pattern ${pattern}" >&2
    exit 1
    ;;
  esac
  exit 0
  ;;
esac

if [ "$1" = "api" ]; then
  case " $* " in
  *" PUT "*)
    if [ -n "${FAKE_PUT_FAILS:-}" ]; then
      echo "fake gh: put failed (HTTP 403)" >&2
      exit 1
    fi
    exit 0
    ;;
  *"Accept: application/vnd.github.raw+json"*)
    printf '%s\n' "${FAKE_TAP_FILE}"
    exit 0
    ;;
  *)
    case "${FAKE_TAP_STATE}" in
    missing)
      echo "gh: Not Found (HTTP 404)" >&2
      exit 1
      ;;
    error)
      echo "gh: Bad Gateway (HTTP 502)" >&2
      exit 1
      ;;
    *)
      echo "abc123"
      exit 0
      ;;
    esac
    ;;
  esac
fi

echo "fake gh: unexpected call: $*" >&2
exit 1
FAKE_GH
chmod +x "${fake_bin}/gh"

export PATH="${fake_bin}:${PATH}"
export GH_TOKEN="release-token"
export TAP_TOKEN="tap-token"

failures=0

# The download directory is random, so it is normalised in the log.
normalise() {
  sed -E 's#--dir [^ ]+#--dir <dir>#'
}

# valid_formula tag version prints a formula in the shape goreleaser
# generates, as the snapshot build in task test:formula shows.
valid_formula() {
  local tag="$1" version="$2"
  local base="https://github.com/ostendorf-cloud/gitcd/releases/download/${tag}"
  cat <<EOF
# typed: false
# frozen_string_literal: true

# This file was generated by GoReleaser. DO NOT EDIT.
class Gitcd < Formula
  desc "Clone repositories into a predictable layout and apply a git identity profile per remote"
  homepage "https://github.com/ostendorf-cloud/gitcd"
  version "${version}"
  license "Apache-2.0"

  depends_on "git"

  on_macos do
    if Hardware::CPU.intel?
      url "${base}/gitcd_darwin_amd64.tar.gz"
      sha256 "1111111111111111111111111111111111111111111111111111111111111111"

      define_method(:install) do
        bin.install "gitcd"
      end
    end
    if Hardware::CPU.arm?
      url "${base}/gitcd_darwin_arm64.tar.gz"
      sha256 "2222222222222222222222222222222222222222222222222222222222222222"

      define_method(:install) do
        bin.install "gitcd"
      end
    end
  end

  on_linux do
    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?
      url "${base}/gitcd_linux_amd64.tar.gz"
      sha256 "3333333333333333333333333333333333333333333333333333333333333333"
      define_method(:install) do
        bin.install "gitcd"
      end
    end
    if Hardware::CPU.arm? && Hardware::CPU.is_64_bit?
      url "${base}/gitcd_linux_arm64.tar.gz"
      sha256 "4444444444444444444444444444444444444444444444444444444444444444"
      define_method(:install) do
        bin.install "gitcd"
      end
    end
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/gitcd version")
  end
end
EOF
}

checksums_for() {
  cat <<'EOF'
1111111111111111111111111111111111111111111111111111111111111111  gitcd_darwin_amd64.tar.gz
2222222222222222222222222222222222222222222222222222222222222222  gitcd_darwin_arm64.tar.gz
3333333333333333333333333333333333333333333333333333333333333333  gitcd_linux_amd64.tar.gz
4444444444444444444444444444444444444444444444444444444444444444  gitcd_linux_arm64.tar.gz
5555555555555555555555555555555555555555555555555555555555555555  gitcd_windows_amd64.zip
EOF
}

sha_of() {
  printf '%s\n' "$1" | shasum -a 256 | cut -d' ' -f1
}

# use_formula tag body points the fake release at body and records the
# hash the release job would have recorded for exactly that body.
use_formula() {
  FAKE_FORMULA="$2"
  export FAKE_FORMULA
  FORMULA_HASHES="$1 $(sha_of "$2")"
  export FORMULA_HASHES
}

reset_fakes() {
  export FAKE_DRAFT=false
  export FAKE_PRERELEASE=false
  export FAKE_TAP_STATE=missing
  FAKE_TAP_FILE="$(valid_formula v0.1.0 0.1.0)"
  export FAKE_TAP_FILE
  FAKE_CHECKSUMS="$(checksums_for)"
  export FAKE_CHECKSUMS
  unset FAKE_VIEW_FAILS FAKE_DOWNLOAD_FAILS FAKE_PUT_FAILS ALLOW_DOWNGRADE VERIFY_MODE
  use_formula v1.0.0 "$(valid_formula v1.0.0 1.0.0)"
}

# run_case name tags want_status want_stderr_substring want_calls
# The remaining behaviour comes from the FAKE_* variables the caller sets.
run_case() {
  local case_name="$1" tags="$2" want_status="$3" want_stderr="$4" want_calls="$5"

  CASE_DIR="${work}/case"
  CALL_LOG="${CASE_DIR}/calls.log"
  export CASE_DIR CALL_LOG
  rm -rf "${CASE_DIR}"
  mkdir -p "${CASE_DIR}"
  : >"${CALL_LOG}"

  local status=0
  TAGS="${tags}" "${script}" >"${CASE_DIR}/stdout" 2>"${CASE_DIR}/stderr" || status=$?

  if [ "${want_status}" = "0" ] && [ "${status}" -ne 0 ]; then
    echo "FAIL ${case_name}: exit status = ${status}, want 0"
    echo "stderr: $(cat "${CASE_DIR}/stderr")"
    failures=$((failures + 1))
    return
  fi
  if [ "${want_status}" != "0" ] && [ "${status}" -eq 0 ]; then
    echo "FAIL ${case_name}: exit status = 0, want non-zero"
    failures=$((failures + 1))
    return
  fi
  if [ -n "${want_stderr}" ] && ! grep -qF -- "${want_stderr}" "${CASE_DIR}/stderr"; then
    echo "FAIL ${case_name}: stderr = $(cat "${CASE_DIR}/stderr"), want it to contain: ${want_stderr}"
    failures=$((failures + 1))
    return
  fi
  local got_calls
  got_calls="$(normalise <"${CALL_LOG}")"
  if [ "${got_calls}" != "${want_calls}" ]; then
    echo "FAIL ${case_name}: calls:"
    echo "${got_calls}"
    echo "want:"
    echo "${want_calls}"
    failures=$((failures + 1))
    return
  fi
  if grep -rqF "tap-token" "${CASE_DIR}/stdout" "${CASE_DIR}/stderr"; then
    echo "FAIL ${case_name}: the tap token reached the output"
    failures=$((failures + 1))
    return
  fi
  echo "PASS ${case_name}"
}

endpoint="repos/ostendorf-cloud/homebrew-tap/contents/Formula/gitcd.rb"
view_jq='"\(.isDraft) \(.isPrerelease)"'
view() { echo "release-token gh release view $1 --json isDraft,isPrerelease --jq ${view_jq}"; }
download() { echo "release-token gh release download $1 --pattern gitcd.rb --dir <dir> --clobber"; }
download_sums() { echo "release-token gh release download $1 --pattern *_checksums.txt --dir <dir> --clobber"; }
get_sha="tap-token gh api ${endpoint}?ref=main --jq .sha"
get_raw="tap-token gh api -H Accept: application/vnd.github.raw+json ${endpoint}?ref=main"
put() { echo "tap-token gh api -X PUT ${endpoint} -f message=gitcd ${1#v} -f branch=main -f content=<base64>"; }
put_end="--silent"

reset_fakes
run_case "nothing released makes no call at all" "" 0 "" ""

reset_fakes
run_case "a missing formula is created without a sha" "v1.0.0" 0 "" \
  "$(view v1.0.0)
$(download v1.0.0)
${get_sha}
$(put v1.0.0) ${put_end}"
if [ "$(cat "${work}/case/put-content")" != "$(printf '%s\n' "${FAKE_FORMULA}" | base64 | tr -d '\n')" ]; then
  echo "FAIL the pushed content is not the downloaded formula"
  failures=$((failures + 1))
else
  echo "PASS the pushed content is the downloaded formula"
fi

reset_fakes
FAKE_TAP_STATE=present
run_case "an outdated formula is updated with the sha it replaces" "v1.0.0" 0 "" \
  "$(view v1.0.0)
$(download v1.0.0)
${get_sha}
${get_raw}
$(put v1.0.0) -f sha=abc123 ${put_end}"

reset_fakes
FAKE_TAP_STATE=present
FAKE_TAP_FILE="${FAKE_FORMULA}"
run_case "an identical formula is left alone, a rerun changes nothing" "v1.0.0" 0 "" \
  "$(view v1.0.0)
$(download v1.0.0)
${get_sha}
${get_raw}"

# The release's own flag decides, never the tag text.
reset_fakes
FAKE_PRERELEASE=true
run_case "a release flagged as pre-release pushes no formula" "v1.0.0" 0 "" "$(view v1.0.0)"

reset_fakes
use_formula "v1.0.0+build-1" "$(valid_formula v1.0.0+build-1 1.0.0+build-1)"
run_case "a hyphen in build metadata is no pre-release" "v1.0.0+build-1" 0 "" \
  "$(view v1.0.0+build-1)
$(download v1.0.0+build-1)
${get_sha}
$(put v1.0.0+build-1) ${put_end}"

# A token that can see a draft gets the draft flag, a read-only token gets
# a 404 for it. Both must stop before anything is downloaded or pushed.
reset_fakes
FAKE_DRAFT=true
run_case "a visible draft release stops before anything is downloaded" "v1.0.0" 1 \
  "is a draft" "$(view v1.0.0)"

reset_fakes
FAKE_DRAFT=hidden
run_case "a draft the read-only token cannot see stops the script" "v1.0.0" 1 \
  "cannot read the release for v1.0.0" "$(view v1.0.0)"

reset_fakes
export FAKE_VIEW_FAILS=1
run_case "an unreadable release stops the script" "v1.0.0" 1 \
  "cannot read the release for v1.0.0" "$(view v1.0.0)"

reset_fakes
export FAKE_DOWNLOAD_FAILS=1
run_case "a missing formula asset stops the script" "v1.0.0" 1 \
  "cannot download gitcd.rb" "$(view v1.0.0)
$(download v1.0.0)"

# What is pushed is the formula the build generated.
reset_fakes
use_formula v1.0.0 "$(valid_formula v1.0.0 1.0.0 | sed 's#github.com/ostendorf-cloud/gitcd/releases#example.invalid/ostendorf-cloud/gitcd/releases#')"
run_case "a formula pointing at another host is refused, even with its own hash" "v1.0.0" 1 \
  "does not match the generated formula" "$(view v1.0.0)
$(download v1.0.0)"

reset_fakes
body="$(valid_formula v1.0.0 1.0.0)"
use_formula v1.0.0 "${body//  license \"Apache-2.0\"/  license \"Apache-2.0\"$'\n'  system \"true\"}"
run_case "a formula with an extra Ruby line is refused, even with its own hash" "v1.0.0" 1 \
  "does not match the generated formula" "$(view v1.0.0)
$(download v1.0.0)"

reset_fakes
use_formula v1.0.0 "$(valid_formula v0.9.0 1.0.0)"
run_case "a formula for another tag is refused" "v1.0.0" 1 \
  "does not match the generated formula" "$(view v1.0.0)
$(download v1.0.0)"

reset_fakes
FAKE_FORMULA="$(valid_formula v1.0.0 1.0.0 | sed 's#3333#3334#')"
run_case "a formula that differs from the recorded hash is refused" "v1.0.0" 1 \
  "differs from the formula the release job generated" "$(view v1.0.0)
$(download v1.0.0)"

reset_fakes
export FORMULA_HASHES=""
run_case "a missing recorded hash stops the script" "v1.0.0" 1 \
  "no formula hash recorded for v1.0.0" "$(view v1.0.0)
$(download v1.0.0)"

reset_fakes
use_formula v1.0.0 "$(valid_formula v1.0.0 1.0.1)"
run_case "a formula with another version than the tag is refused" "v1.0.0" 1 \
  "does not carry the version 1.0.0" "$(view v1.0.0)
$(download v1.0.0)"

# The manual run, verified against the release's own checksums file.
reset_fakes
export VERIFY_MODE=checksums
export FORMULA_HASHES=""
run_case "the checksums mode accepts a formula that agrees with the release" "v1.0.0" 0 "" \
  "$(view v1.0.0)
$(download v1.0.0)
$(download_sums v1.0.0)
${get_sha}
$(put v1.0.0) ${put_end}"

reset_fakes
export VERIFY_MODE=checksums
export FORMULA_HASHES=""
FAKE_FORMULA="$(valid_formula v1.0.0 1.0.0 | sed 's#3333#3334#')"
run_case "the checksums mode refuses a checksum the release does not list" "v1.0.0" 1 \
  "is not the one the release lists" "$(view v1.0.0)
$(download v1.0.0)
$(download_sums v1.0.0)"

reset_fakes
export VERIFY_MODE=checksums
export FORMULA_HASHES=""
FAKE_CHECKSUMS="$(checksums_for | grep -v darwin_arm64)"
run_case "the checksums mode refuses an archive the release does not list at all" "v1.0.0" 1 \
  "is not the one the release lists" "$(view v1.0.0)
$(download v1.0.0)
$(download_sums v1.0.0)"

reset_fakes
export VERIFY_MODE=checksums
export FORMULA_HASHES=""
use_formula v1.0.0 "$(valid_formula v1.0.0 1.0.0 | sed 's#github.com/ostendorf-cloud/gitcd/releases#example.invalid/ostendorf-cloud/gitcd/releases#')"
export FORMULA_HASHES=""
run_case "the checksums mode still checks the formula's structure" "v1.0.0" 1 \
  "does not match the generated formula" "$(view v1.0.0)
$(download v1.0.0)
$(download_sums v1.0.0)"

reset_fakes
export VERIFY_MODE=bogus
run_case "an unknown verify mode stops the script" "v1.0.0" 1 "unknown VERIFY_MODE" ""

reset_fakes
run_case "a tag that is not a release tag is refused" "v1.0.0;x" 1 \
  "is not a release tag" ""

# The tap never goes backwards.
reset_fakes
FAKE_TAP_STATE=present
FAKE_TAP_FILE="$(valid_formula v2.0.0 2.0.0)"
run_case "an older release does not replace a newer formula" "v1.0.0" 1 \
  "refusing to put an older formula back" "$(view v1.0.0)
$(download v1.0.0)
${get_sha}
${get_raw}"

reset_fakes
FAKE_TAP_STATE=present
FAKE_TAP_FILE="$(valid_formula v2.0.0 2.0.0)"
export ALLOW_DOWNGRADE=true
run_case "an explicit input lets an older release through" "v1.0.0" 0 "" \
  "$(view v1.0.0)
$(download v1.0.0)
${get_sha}
${get_raw}
$(put v1.0.0) -f sha=abc123 ${put_end}"

reset_fakes
FAKE_TAP_STATE=present
FAKE_TAP_FILE="$(valid_formula v0.9.0 0.9.0)"
run_case "a newer release replaces an older formula" "v1.0.0" 0 "" \
  "$(view v1.0.0)
$(download v1.0.0)
${get_sha}
${get_raw}
$(put v1.0.0) -f sha=abc123 ${put_end}"

reset_fakes
FAKE_TAP_STATE=present
FAKE_TAP_FILE="$(valid_formula v1.10.0 1.10.0)"
use_formula v1.9.0 "$(valid_formula v1.9.0 1.9.0)"
run_case "versions compare numerically, 1.10.0 is newer than 1.9.0" "v1.9.0" 1 \
  "refusing to put an older formula back" "$(view v1.9.0)
$(download v1.9.0)
${get_sha}
${get_raw}"

reset_fakes
FAKE_TAP_STATE=present
FAKE_TAP_FILE="$(valid_formula v1.0.0+build-1 1.0.0+build-1)"
run_case "sort -V is not semver: build metadata ranks above the plain version" "v1.0.0" 1 \
  "refusing to put an older formula back" "$(view v1.0.0)
$(download v1.0.0)
${get_sha}
${get_raw}"

reset_fakes
FAKE_TAP_STATE=error
run_case "a tap read error is not mistaken for a missing formula" "v1.0.0" 1 \
  "cannot read Formula/gitcd.rb" "$(view v1.0.0)
$(download v1.0.0)
${get_sha}"

reset_fakes
export FAKE_PUT_FAILS=1
run_case "a failed push fails the script and says to rerun" "v1.0.0" 1 \
  "rerun the failed jobs" "$(view v1.0.0)
$(download v1.0.0)
${get_sha}
$(put v1.0.0) ${put_end}"

finished=yes
if [ "${failures}" -ne 0 ]; then
  echo "${failures} test(s) failed"
  exit 1
fi

echo "all tests passed"
