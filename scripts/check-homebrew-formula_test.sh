# Table driven tests for check-homebrew-formula.sh: one accepted formula, in
# the shape goreleaser generates, and a list of altered formulas that must
# each be rejected. The real snapshot formula is accepted by
# "task test:formula", which runs the same script on it.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
validator="${script_dir}/check-homebrew-formula.sh"
# An explicit template, because macOS mktemp ignores TMPDIR without one.
work="$(mktemp -d "${TMPDIR:-/tmp}/check-homebrew-formula-test.XXXXXXXX")"
finished=no
# An old bash can stop a script on an expansion it does not know and still
# exit 0, so a run that did not reach its last line fails here.
trap 'rm -rf "${work}"; if [ "${finished}" != yes ]; then if [ "${failures:-0}" -eq 0 ]; then echo "test script stopped before its last line" >&2; fi; exit 1; fi' EXIT

tag="v1.0.0"
file="${work}/gitcd.rb"
failures=0

base_url="https://github.com/ostendorf-cloud/gitcd/releases/download/${tag}"
url1="      url \"${base_url}/gitcd_darwin_amd64.tar.gz\""
sha1='      sha256 "1111111111111111111111111111111111111111111111111111111111111111"'

base="$(
  cat <<EOF
# typed: false
# frozen_string_literal: true

# This file was generated by GoReleaser. DO NOT EDIT.
class Gitcd < Formula
  desc "Clone repositories into a predictable layout and set a git identity per remote"
  homepage "https://github.com/ostendorf-cloud/gitcd"
  version "1.0.0"
  license "Apache-2.0"

  depends_on "git"

  on_macos do
    if Hardware::CPU.intel?
${url1}
${sha1}

      define_method(:install) do
        bin.install "gitcd"
      end
    end
    if Hardware::CPU.arm?
      url "${base_url}/gitcd_darwin_arm64.tar.gz"
      sha256 "2222222222222222222222222222222222222222222222222222222222222222"

      define_method(:install) do
        bin.install "gitcd"
      end
    end
  end

  on_linux do
    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?
      url "${base_url}/gitcd_linux_amd64.tar.gz"
      sha256 "3333333333333333333333333333333333333333333333333333333333333333"
      define_method(:install) do
        bin.install "gitcd"
      end
    end
    if Hardware::CPU.arm? && Hardware::CPU.is_64_bit?
      url "${base_url}/gitcd_linux_arm64.tar.gz"
      sha256 "4444444444444444444444444444444444444444444444444444444444444444"
      define_method(:install) do
        bin.install "gitcd"
      end
    end
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/gitcd version")
  end
end
EOF
)"

# s text old new replaces the first occurrence of old, sa every occurrence.
# The pattern and the replacement come through variables, which every bash
# the repository runs on expands the same way.
s() {
  local text="$1" old="$2" new="$3"
  printf '%s' "${text/$old/$new}"
}
sa() {
  local text="$1" old="$2" new="$3"
  printf '%s' "${text//$old/$new}"
}

# run_check name want body [tag]: body is written with a trailing newline.
run_check() {
  local name="$1" want="$2" body="$3" check_tag="${4:-${tag}}"
  printf '%s\n' "${body}" >"${file}"
  report "${name}" "${want}" "${check_tag}"
}

# report name want tag checks the formula already in ${file}.
report() {
  local name="$1" want="$2" check_tag="$3" status=0
  "${validator}" "${file}" "${check_tag}" >/dev/null 2>"${work}/stderr" || status=$?
  if [ "${want}" = "accept" ] && [ "${status}" -ne 0 ]; then
    echo "FAIL ${name}: rejected, want accepted: $(cat "${work}/stderr")"
    failures=$((failures + 1))
    return
  fi
  if [ "${want}" = "reject" ] && [ "${status}" -eq 0 ]; then
    echo "FAIL ${name}: accepted, want rejected"
    failures=$((failures + 1))
    return
  fi
  echo "PASS ${name}"
}

accept() { run_check "$1" accept "$2" "${3:-}"; }
reject() { run_check "$1" reject "$2" "${3:-}"; }

license='  license "Apache-2.0"'
homepage='  homepage "https://github.com/ostendorf-cloud/gitcd"'
depends='  depends_on "git"'
version='  version "1.0.0"'
nl=$'\n'

accept "the generated formula is accepted" "${base}"

# Code smuggled into a line the template has.
reject "code after a semicolon on a url line" "$(s "${base}" "${url1}" "${url1}; system \"x\"")"
reject "a comment on a url line" "$(s "${base}" "${url1}" "${url1} # x")"
reject "code after a semicolon after the closing end" "${base%end}end; system \"x\""
reject "a heredoc" "$(s "${base}" "${homepage}" "  system <<~EOS${nl}  x${nl}  EOS${nl}${homepage}")"
reject "a backslash line continuation" "$(s "${base}" "${license}" "${license} \\")"
reject "code after the end" "${base}${nl}system \"x\""
reject "an __END__ marker" "${base}${nl}__END__${nl}x"
reject "a post_install hook" "$(s "${base}" "  test do" "  def post_install${nl}    system \"x\"${nl}  end${nl}${nl}  test do")"
reject "a second class with another name" "${base}${nl}class Evil < Formula${nl}end"
reject "a second class with the same name" "${base}${nl}class Gitcd < Formula${nl}end"
reject "a second description" "$(s "${base}" "${homepage}" "  desc \"x\"${nl}${homepage}")"
reject "a missing dependency line" "$(s "${base}" "${depends}" "")"

# Characters that look like the template, or hide from a line reader.
reject "a carriage return at the end of every line" "$(sa "${base}" "${nl}" $'\r\n')"
reject "a tab in a line" "$(s "${base}" "${depends}" $'\tdepends_on "git"')"
reject "a trailing space" "$(s "${base}" "${depends}" "${depends} ")"
reject "a Cyrillic look-alike in the host" "$(s "${base}" "${url1}" "$(s "${url1}" github $'g\xd1\x96thub')")"
reject "fullwidth quotes" "$(s "${base}" "${depends}" $'  depends_on \xef\xbc\x82git\xef\xbc\x82')"
reject "a vertical tab" "$(s "${base}" "${depends}" "${depends}"$'\v')"
reject "a form feed" "$(s "${base}" "${depends}" "${depends}"$'\f')"
reject "an end of transmission byte inside a line" "$(s "${base}" "${depends}" "${depends}"$'\x04')"

printf '\xef\xbb\xbf%s\n' "${base}" >"${file}"
report "a byte order mark" reject "${tag}"

printf '%s\n\0' "${base}" >"${file}"
report "a NUL byte after the formula" reject "${tag}"

{
  printf '%s\n' "${base%end}"
  printf 'end\0; system "x"\n'
} >"${file}"
report "a NUL byte hiding code at the end of a line" reject "${tag}"

marked="$(s "${base}" "${license}" "${license}@@NUL@@")"
{
  printf '%s' "${marked%%@@NUL@@*}"
  printf '\0; system "x"'
  printf '%s\n' "${marked#*@@NUL@@}"
} >"${file}"
report "a NUL byte hiding code in the middle of the formula" reject "${tag}"

printf '%s' "${base%end}end; system \"x\"" >"${file}"
report "code on the last line without a newline" reject "${tag}"

# URLs: host, tag, shape.
reject "another host" "$(s "${base}" "${url1}" "$(s "${url1}" github.com example.invalid)")"
reject "userinfo in the url" "$(s "${base}" "${url1}" "$(s "${url1}" "https://" "https://ostendorf-cloud@")")"
reject "a query string in the url" "$(s "${base}" "${url1}" "${url1%\"}?x=1\"")"
reject "another tag in the urls" "$(sa "${base}" v1.0.0 v1.0.1)"
reject "a tag whose dots are not literal" "$(sa "${base}" v1.0.0 v1x0x0)"
reject "the formula checked for another tag" "${base}" "v1.0.1"
reject "a url that is not an archive of a known platform" "$(s "${base}" gitcd_darwin_amd64 gitcd_freebsd_amd64)"
reject "a url that repeats one platform and drops another" "$(s "${base}" gitcd_linux_arm64 gitcd_linux_amd64)"
swapped="$(s "${base}" "  on_macos do" "@@")"
swapped="$(s "${swapped}" "  on_linux do" "  on_macos do")"
reject "a darwin url inside on_linux" "$(s "${swapped}" "@@" "  on_linux do")"
reject "a url outside any block" "$(s "${base}" "  on_macos do" "")"

# Repeated or trailing lines the counts exist for.
descline='  desc "Clone repositories into a predictable layout and set a git identity per remote"'
reject "a duplicated identical description" "$(s "${base}" "${descline}" "${descline}${nl}${descline}")"
reject "a blank line after the final end" "${base}${nl}"

# Reorderings. Every line stays one the template has, Ruby ignores the
# indentation, so only the comparison with the skeleton rejects these.
reject "the CPU guards dropped, the last url per system winning" \
  "$(printf '%s\n' "${base}" | grep -v -E '^    (if Hardware::.*|end)$')"

assertline='    assert_match version.to_s, shell_output("#{bin}/gitcd version")'
reject "depends_on moved into the test block" \
  "$(s "$(s "${base}" "${depends}${nl}" "")" "  test do" "  test do${nl}${depends}")"
installline='        bin.install "gitcd"'
reject "the test assertion moved into install" \
  "$(s "$(s "${base}" "${assertline}${nl}" "")" "${installline}" "${installline}${nl}${assertline}")"

head_part="${base%%  on_macos do*}"
after_mac="${base#*  on_macos do}"
mac_body="${after_mac%%  on_linux do*}"
after_linux="${after_mac#*  on_linux do}"
linux_body="${after_linux%%  test do*}"
tail_part="  test do${after_linux#*  test do}"
reject "the on_macos and on_linux blocks in the other order" \
  "${head_part}  on_linux do${linux_body}  on_macos do${mac_body}${tail_part}"

arm_line='    if Hardware::CPU.arm?'
marked_end="$(s "${mac_body}" "${nl}  end${nl}" "@@END@@")"
mac_inner="${marked_end%%@@END@@*}"
mac_closing="${marked_end#*@@END@@}"
marked_arm="$(s "${mac_inner}" "${arm_line}" "@@ARM@@")"
mac_intel="${marked_arm%%@@ARM@@*}"
mac_arm="${arm_line}${marked_arm#*@@ARM@@}"
reject "the arm64 and amd64 blocks swapped inside on_macos" \
  "${head_part}  on_macos do${nl}${mac_arm}${mac_intel}  end${nl}${mac_closing}  on_linux do${linux_body}${tail_part}"

# Which archive sits under which CPU guard: the url and sha256 pairs swapped,
# guards kept, so the skeleton comparison sees nothing wrong.
swap_pairs() {
  local text="$1" os="$2" first_sha="$3" second_sha="$4"
  text="$(sa "${text}" "gitcd_${os}_amd64" "@@AMD@@")"
  text="$(sa "${text}" "gitcd_${os}_arm64" "gitcd_${os}_amd64")"
  text="$(sa "${text}" "@@AMD@@" "gitcd_${os}_arm64")"
  text="$(sa "${text}" "${first_sha}" "@@SHA@@")"
  text="$(sa "${text}" "${second_sha}" "${first_sha}")"
  sa "${text}" "@@SHA@@" "${second_sha}"
}
sha_of_digit() { printf '%064d' 0 | tr 0 "$1"; }
reject "the amd64 and arm64 archives swapped under the guards in on_macos" \
  "$(swap_pairs "${base}" darwin "$(sha_of_digit 1)" "$(sha_of_digit 2)")"
reject "the amd64 and arm64 archives swapped under the guards in on_linux" \
  "$(swap_pairs "${base}" linux "$(sha_of_digit 3)" "$(sha_of_digit 4)")"

# sha256 lines.
reject "a url without its sha256" "$(s "${base}" "${sha1}${nl}" "")"
reject "an extra sha256 line" "$(s "${base}" "${sha1}" "${sha1}${nl}${sha1}")"
reject "a sha256 that is not 64 lower case hex digits" "$(s "${base}" "${sha1}" '      sha256 "ABC"')"

# The version line.
reject "no version line" "$(s "${base}" "${version}" "")"
reject "two version lines" "$(s "${base}" "${version}" "${version}${nl}${version}")"
reject "a version with an interpolation" "$(s "${base}" "${version}" '  version "1.0.0#{x}"')"
reject "a version with a quote" "$(s "${base}" "${version}" '  version "1.0.0"x"')"

if [ "${failures}" -ne 0 ]; then
  finished=yes
  echo "${failures} test(s) failed"
  exit 1
fi

finished=yes
echo "all tests passed"
