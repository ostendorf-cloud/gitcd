// Package gitconfig renders the git configuration files gitcd generates
// for its identity profiles: one file per profile and one file tying them
// to the configured rules through includeIf. It only renders content, as a
// string; it never writes a file or shells out to git. Every write goes
// through internal/git, from the command layer.
package gitconfig

import (
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/ostendorf-cloud/gitcd/internal/config"
	"github.com/ostendorf-cloud/gitcd/internal/profile"
)

// generatedHeader is written at the top of every file this package
// renders, so a user who opens one by hand knows not to edit it.
const generatedHeader = "# Generated by \"gitcd apply\". Edits here are overwritten the next time it runs.\n"

// Dir returns the directory gitcd owns and regenerates, under home, the
// user's home directory.
func Dir(home string) string {
	return filepath.Join(home, ".config", "gitcd")
}

// ProfilesDir returns the directory a profile's own rendered file lives
// under, under home.
func ProfilesDir(home string) string {
	return filepath.Join(Dir(home), "profiles")
}

// ProfilePath returns the path "apply" renders profile name's file to,
// under home.
func ProfilePath(home, name string) string {
	return filepath.Join(ProfilesDir(home), name+".gitconfig")
}

// IncludePath returns the path "apply" renders the include file to, and
// "init" adds to the user's global git configuration, under home.
func IncludePath(home string) string {
	return filepath.Join(Dir(home), "includes.gitconfig")
}

// Rendered is every file "gitcd apply" writes, keyed by its absolute path.
type Rendered map[string]string

// Render renders every profile file and the include file for cfg, with
// every path resolved under home.
//
// cfg is validated in full before anything is rendered, through
// config.Config.Validate, the same gate Load applies to a configuration
// file. Render is exported and takes a config.Config, so a caller can
// build one by hand, and what this map holds is what "apply" then
// writes: every profile name that decides a path, every rule field and
// host alias and layout that decides a condition, and every key and
// value that decides file content has to be acceptable before any of it
// is turned into a file.
func Render(cfg config.Config, home string) (Rendered, error) {
	if err := cfg.Validate(); err != nil {
		return nil, fmt.Errorf("gitconfig: %w", err)
	}

	out := Rendered{}

	names := make([]string, 0, len(cfg.Profiles))
	for name := range cfg.Profiles {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		content, err := RenderProfile(cfg.Profiles[name], cfg.UseConfigOnly)
		if err != nil {
			return nil, fmt.Errorf("gitconfig: render profile %q: %w", name, err)
		}
		out[ProfilePath(home, name)] = content
	}

	out[IncludePath(home)] = renderIncludes(cfg, home)
	return out, nil
}

// RenderProfile renders one profile's git configuration file content.
//
// Every key's syntax and every value's characters are validated here as
// well as at load time: this function is exported and takes a
// config.Profile, so a caller can hand it a map it built itself, and a
// key or value that cannot be rendered correctly must fail here rather
// than render into a file that parses as something other than what it
// says.
//
// The opt in a restricted key needs is deliberately not applied here. A
// config.Profile carries no allow list, so this function cannot tell a
// key that was opted in from one that was not; that gate belongs to the
// configuration as a whole and is applied by config.Config.Validate,
// which both Load and Render call.
//
// When useConfigOnly is true and the profile does not already set its own
// "user.useConfigOnly", "true" is added: a repository whose identity gitcd
// cannot determine then refuses to commit rather than falling back to a
// machine wide identity.
func RenderProfile(p config.Profile, useConfigOnly bool) (string, error) {
	entries := make(map[string]string, len(p)+1)
	for k, v := range p {
		entries[k] = v
	}
	if useConfigOnly {
		if _, ok := entries["user.useConfigOnly"]; !ok {
			entries["user.useConfigOnly"] = "true"
		}
	}

	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString(generatedHeader)
	currentSection, currentSubsection := "", ""
	wroteHeader := false
	for _, key := range keys {
		if err := config.ValidateProfileKey(key); err != nil {
			return "", fmt.Errorf("gitconfig: %w", err)
		}
		if err := config.ValidateProfileValue(entries[key]); err != nil {
			return "", fmt.Errorf("gitconfig: key %q: %w", key, err)
		}
		section, subsection, name, err := config.SplitKey(key)
		if err != nil {
			return "", fmt.Errorf("gitconfig: %w", err)
		}
		if !wroteHeader || section != currentSection || subsection != currentSubsection {
			if subsection == "" {
				fmt.Fprintf(&b, "[%s]\n", section)
			} else {
				fmt.Fprintf(&b, "[%s \"%s\"]\n", section, subsection)
			}
			currentSection, currentSubsection = section, subsection
			wroteHeader = true
		}
		fmt.Fprintf(&b, "\t%s = %s\n", name, quoteValue(entries[key]))
	}
	return b.String(), nil
}

// renderIncludes renders the include file: an unconditional
// "user.useConfigOnly" when cfg.UseConfigOnly is set, then one plain
// "[include]" for cfg.DefaultProfile, then one "[includeIf]" block per URL
// form and one "[includeIf \"gitdir/i:...\"]" block, per rule, in ascending
// specificity order, so a later, more specific block always wins over an
// earlier, less specific one, regardless of the configuration file's own
// rule order.
//
// The unconditional block is load bearing, not decorative: every other
// "useConfigOnly" this package writes sits inside a profile file, reached
// only through an includeIf condition, so it only ever applies to a
// repository some rule, or the default profile, already matches. A
// repository no rule matches, and no default profile covers, reaches
// neither, so without this unconditional copy it carries no
// "useConfigOnly" at all, and git falls back to guessing an identity from
// the account's username and hostname, silently, exactly the outcome a
// repository with an undetermined identity is supposed to refuse.
// Verified directly against git 2.54.0: with this block removed, a
// repository under neither a rule nor a default profile committed
// successfully under a guessed identity despite every profile file
// itself setting "useConfigOnly = true".
//
// Every input that reaches a condition here is validated by
// config.Config.Validate, which Render calls before this runs: a rule's
// host, owner and repo, the profile name each path is built from, the
// host aliases hasconfigGlobs interpolates, and the layout template
// renderGitdirGlob interpolates. None of the four is written as a value,
// so neither quoting nor escaping applies to any of them: one holding a
// quote would close the condition, and one holding a glob metacharacter
// would match repositories the rule does not name.
func renderIncludes(cfg config.Config, home string) string {
	var b strings.Builder
	b.WriteString(generatedHeader)

	if cfg.UseConfigOnly {
		b.WriteString("\n[user]\n\tuseConfigOnly = true\n")
	}

	if cfg.DefaultProfile != "" {
		fmt.Fprintf(&b, "\n[include]\n\tpath = %s\n", quoteValue(ProfilePath(home, cfg.DefaultProfile)))
	}

	for _, rule := range profile.SortRules(cfg.Rules) {
		path := ProfilePath(home, rule.Profile)

		gitdirGlob := renderGitdirGlob(cfg, rule)
		fmt.Fprintf(&b, "\n[includeIf \"gitdir/i:%s\"]\n\tpath = %s\n", gitdirGlob, quoteValue(path))

		for _, urlGlob := range hasconfigGlobs(cfg, rule) {
			fmt.Fprintf(&b, "\n[includeIf \"hasconfig:remote.*.url:%s\"]\n\tpath = %s\n", urlGlob, quoteValue(path))
		}
	}

	return b.String()
}

// placeholderPattern matches a layout template placeholder, the same
// shape internal/layout renders: "{host}", "{owner}" ("{org}" a synonym),
// "{project}" and "{repo}".
var placeholderPattern = regexp.MustCompile(`\{(\w+)\}`)

// renderGitdirGlob renders rule's layout template into a "gitdir/i"
// pattern: every field the rule pins is substituted literally, every field
// it leaves open, including "project", which no rule carries, becomes "*",
// and the whole pattern is rooted at cfg.Root with a trailing "/**", so it
// also catches a repository whose remote was renamed or removed after
// gitcd cloned it there.
func renderGitdirGlob(cfg config.Config, rule config.Rule) string {
	tmpl := cfg.LayoutFor(rule.Host)
	rendered := placeholderPattern.ReplaceAllStringFunc(tmpl, func(m string) string {
		name := placeholderPattern.FindStringSubmatch(m)[1]
		switch name {
		case "host":
			return rule.Host
		case "owner", "org":
			if rule.Owner == "" {
				return "*"
			}
			return rule.Owner
		case "repo":
			if rule.Repo == "" {
				return "*"
			}
			return rule.Repo
		default:
			return "*"
		}
	})
	return filepath.Join(cfg.Root, rendered) + "/**"
}

// azureDevOpsHost is the canonical host name Azure DevOps rules are
// configured under, matching the hardcoded spelling internal/remote and
// internal/config both already key their own Azure DevOps handling on.
const azureDevOpsHost = "dev.azure.com"

// hasconfigGlobs returns one "hasconfig:remote.*.url" glob per URL form a
// user could have a rule's host stored as, so that every form
// remote.Parse accepts and resolves to this host, the host's configured
// aliases included, is caught by some glob here: the two must agree, or a
// repository outside the layout root, which only a "hasconfig" block
// protects, silently falls through to the default profile.
//
// A host is reached under its canonical name or any of its configured SSH
// host aliases alike, since an alias is exactly how a second account on
// one forge is driven, through a distinct SSH host bound to a distinct
// key; every form below is therefore rendered once per name in that set.
// For each name, four forms are emitted: the scp style SSH form
// ("git@host:path"), the explicit "ssh://" form ("ssh://git@host/path"),
// plain HTTPS ("https://host/path") and HTTPS carrying userinfo
// ("https://*@host/path"), since remote.Parse's classify strips any
// "user@" prefix before the colon or the host, so the literal user never
// decides the host, yet git stores the remote exactly as written: a
// repository cloned with a username in its HTTPS URL, Azure DevOps's own
// convention, or an explicit git@ SSH user never matches the plain forms.
// Azure DevOps offers no "ssh://" URL at all, only the scp form, so that
// form is skipped for it.
//
// When rule pins a repo, the owner and repo segment is matched literally,
// once with and once without a trailing ".git", since either is a valid
// stored remote; when it pins only an owner, the glob ends in "**", to
// match every repository under that owner; with neither, it matches every
// repository under the host.
//
// Azure DevOps carries a project segment between the owner and the
// repository that no rule can pin, since config.Rule has no field for it;
// its path shape also differs by protocol, "v3/<owner>/<project>/<repo>"
// over SSH against "<owner>/<project>/_git/<repo>" over HTTPS. Both are
// handled by wildcarding the project segment instead of matching it, and,
// when the rule pins only an owner or neither, the open "**" already used
// for every other host also happens to swallow the project segment, so no
// Azure specific shape is needed there.
//
// The scp form's host only tier needs its own path, distinct from every
// other tier and every other form: verified directly against git 2.54.0,
// "hasconfig" matches with wildmatch(3) without FNM_PATHNAME, but that
// flag is not what decides whether "**" crosses a "/": wildmatch only
// gives "**" its cross slash meaning when a "/" bounds it on both sides,
// or when it begins the whole pattern or follows one. Every other glob
// here has a "/" sitting right before its trailing "**", from the
// pattern's own path separator, so it crosses slashes correctly; the scp
// host only glob has a bare "**" straight after the literal ":", with no
// "/" in front of it, so it behaves as a single, non crossing segment and
// never matches a real "owner/repo" remote. scpRepoPathVariants supplies
// the missing leading segment and slash for that one tier.
func hasconfigGlobs(cfg config.Config, rule config.Rule) []string {
	azure := rule.Host == azureDevOpsHost

	hosts := []string{rule.Host}
	hosts = append(hosts, cfg.Hosts[rule.Host].Aliases...)

	var globs []string
	for _, host := range hosts {
		for _, p := range scpRepoPathVariants(rule.Owner, rule.Repo, azure) {
			globs = append(globs, fmt.Sprintf("git@%s:%s", host, p))
		}
		if !azure {
			for _, p := range sshRepoPathVariants(rule.Owner, rule.Repo, azure) {
				globs = append(globs, fmt.Sprintf("ssh://git@%s/%s", host, p))
			}
		}
		for _, p := range httpsRepoPathVariants(rule.Owner, rule.Repo, azure) {
			globs = append(globs, fmt.Sprintf("https://%s/%s", host, p))
			globs = append(globs, fmt.Sprintf("https://*@%s/%s", host, p))
		}
	}
	return globs
}

// scpRepoPathVariants is sshRepoPathVariants for the scp style
// "git@host:path" form specifically, differing only in the host only
// tier, neither owner nor repo pinned: there, sshRepoPathVariants'
// trailing "**" would sit straight after the form's own literal ":",
// with no "/" in front of it to give it cross slash meaning, so it would
// match a single path segment only and never a real "owner/repo" remote.
// "*/**" matches that owner segment, whatever it is, then crosses every
// slash after it, a GitLab style "group/subgroup/repo" path included.
// Every other tier already has a "/" immediately before its own "**",
// from the owner segment or, for Azure DevOps, the literal "v3" prefix,
// so sshRepoPathVariants' path is already correct there.
func scpRepoPathVariants(owner, repo string, azure bool) []string {
	if !azure && owner == "" && repo == "" {
		return []string{"*/**"}
	}
	return sshRepoPathVariants(owner, repo, azure)
}

// sshRepoPathVariants returns the path segment, after "host:" or
// "host/", the scp style and "ssh://" forms carry for owner and repo.
// Azure DevOps's SSH path adds the literal "v3" prefix and, once a repo is
// pinned, a wildcard where its project segment sits, which the SSH path
// never omits and a rule never pins; it carries no ".git" suffix, unlike
// every other host.
func sshRepoPathVariants(owner, repo string, azure bool) []string {
	if !azure {
		return repoPathVariants(owner, repo)
	}
	switch {
	case repo != "":
		return []string{"v3/" + owner + "/*/" + repo}
	case owner != "":
		return []string{"v3/" + owner + "/**"}
	default:
		return []string{"v3/**"}
	}
}

// httpsRepoPathVariants is sshRepoPathVariants for the HTTPS path, which
// carries no "v3" prefix but does carry the literal "_git" segment right
// before the repository, once a repo is pinned.
func httpsRepoPathVariants(owner, repo string, azure bool) []string {
	if !azure {
		return repoPathVariants(owner, repo)
	}
	switch {
	case repo != "":
		return []string{owner + "/*/_git/" + repo}
	case owner != "":
		return []string{owner + "/**"}
	default:
		return []string{"**"}
	}
}

// repoPathVariants is the non Azure DevOps path shape shared by the scp
// style, "ssh://" and HTTPS forms.
func repoPathVariants(owner, repo string) []string {
	switch {
	case repo != "":
		base := owner + "/" + repo
		return []string{base, base + ".git"}
	case owner != "":
		return []string{owner + "/**"}
	default:
		return []string{"**"}
	}
}

// quoteValue double quotes value for use as a git config value or path,
// escaping the characters that would otherwise end the value early or be
// read back as something else. Quoting is always valid git config syntax,
// so this never needs to special case a value that happens not to need
// it.
//
// The backslash and the quote are escaped because quoting itself
// introduces them. The three control characters are escaped because a
// value is written on one line: a line break inside the quotes ends the
// line rather than the value, and git then refuses the whole file, which
// for a file reached through an include means every git command in every
// repository the include matches fails until it is repaired by hand.
// Verified against git 2.54.0: "\n", "\t" and "\b" read back as the
// control character, a literal line break inside the quotes does not
// parse at all. Every other control character has no escape git reads
// back, so config.ValidateProfileValue refuses it instead, and
// RenderProfile applies that gate before reaching here.
func quoteValue(value string) string {
	replacer := strings.NewReplacer(
		`\`, `\\`,
		`"`, `\"`,
		"\n", `\n`,
		"\t", `\t`,
		"\b", `\b`,
	)
	return `"` + replacer.Replace(value) + `"`
}
