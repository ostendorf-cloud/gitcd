// Package gitconfig renders the git configuration files gitcd generates
// for its identity profiles: one file per profile and one file tying them
// to the configured rules through includeIf. It only renders content, as a
// string; it never writes a file or shells out to git. Every write goes
// through internal/git, from the command layer.
package gitconfig

import (
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/ostendorf-cloud/gitcd/internal/config"
	"github.com/ostendorf-cloud/gitcd/internal/profile"
)

// generatedHeader is written at the top of every file this package
// renders, so a user who opens one by hand knows not to edit it.
const generatedHeader = "# Generated by \"gitcd apply\". Edits here are overwritten the next time it runs.\n"

// Dir returns the directory gitcd owns and regenerates, under home, the
// user's home directory.
func Dir(home string) string {
	return filepath.Join(home, ".config", "gitcd")
}

// ProfilesDir returns the directory a profile's own rendered file lives
// under, under home.
func ProfilesDir(home string) string {
	return filepath.Join(Dir(home), "profiles")
}

// ProfilePath returns the path "apply" renders profile name's file to,
// under home.
func ProfilePath(home, name string) string {
	return filepath.Join(ProfilesDir(home), name+".gitconfig")
}

// IncludePath returns the path "apply" renders the include file to, and
// "init" adds to the user's global git configuration, under home.
func IncludePath(home string) string {
	return filepath.Join(Dir(home), "includes.gitconfig")
}

// Rendered is every file "gitcd apply" writes, keyed by its absolute path.
type Rendered map[string]string

// Render renders every profile file and the include file for cfg, with
// every path resolved under home.
func Render(cfg config.Config, home string) (Rendered, error) {
	out := Rendered{}

	names := make([]string, 0, len(cfg.Profiles))
	for name := range cfg.Profiles {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		content, err := RenderProfile(cfg.Profiles[name], cfg.UseConfigOnly)
		if err != nil {
			return nil, fmt.Errorf("gitconfig: render profile %q: %w", name, err)
		}
		out[ProfilePath(home, name)] = content
	}

	out[IncludePath(home)] = renderIncludes(cfg, home)
	return out, nil
}

// RenderProfile renders one profile's git configuration file content. When
// useConfigOnly is true and the profile does not already set its own
// "user.useConfigOnly", "true" is added: a repository whose identity gitcd
// cannot determine then refuses to commit rather than falling back to a
// machine wide identity.
func RenderProfile(p config.Profile, useConfigOnly bool) (string, error) {
	entries := make(map[string]string, len(p)+1)
	for k, v := range p {
		entries[k] = v
	}
	if useConfigOnly {
		if _, ok := entries["user.useConfigOnly"]; !ok {
			entries["user.useConfigOnly"] = "true"
		}
	}

	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString(generatedHeader)
	currentSection, currentSubsection := "", ""
	wroteHeader := false
	for _, key := range keys {
		section, subsection, name, err := splitKey(key)
		if err != nil {
			return "", err
		}
		if !wroteHeader || section != currentSection || subsection != currentSubsection {
			if subsection == "" {
				fmt.Fprintf(&b, "[%s]\n", section)
			} else {
				fmt.Fprintf(&b, "[%s \"%s\"]\n", section, subsection)
			}
			currentSection, currentSubsection = section, subsection
			wroteHeader = true
		}
		fmt.Fprintf(&b, "\t%s = %s\n", name, quoteValue(entries[key]))
	}
	return b.String(), nil
}

// renderIncludes renders the include file: one plain "[include]" for
// cfg.DefaultProfile, then one "[includeIf]" block per URL form and one
// "[includeIf \"gitdir/i:...\"]" block, per rule, in ascending specificity
// order, so a later, more specific block always wins over an earlier, less
// specific one, regardless of the configuration file's own rule order.
func renderIncludes(cfg config.Config, home string) string {
	var b strings.Builder
	b.WriteString(generatedHeader)

	if cfg.DefaultProfile != "" {
		fmt.Fprintf(&b, "\n[include]\n\tpath = %s\n", quoteValue(ProfilePath(home, cfg.DefaultProfile)))
	}

	for _, rule := range profile.SortRules(cfg.Rules) {
		path := ProfilePath(home, rule.Profile)

		gitdirGlob := renderGitdirGlob(cfg, rule)
		fmt.Fprintf(&b, "\n[includeIf \"gitdir/i:%s\"]\n\tpath = %s\n", gitdirGlob, quoteValue(path))

		for _, urlGlob := range hasconfigGlobs(rule) {
			fmt.Fprintf(&b, "\n[includeIf \"hasconfig:remote.*.url:%s\"]\n\tpath = %s\n", urlGlob, quoteValue(path))
		}
	}

	return b.String()
}

// placeholderPattern matches a layout template placeholder, the same
// shape internal/layout renders: "{host}", "{owner}" ("{org}" a synonym),
// "{project}" and "{repo}".
var placeholderPattern = regexp.MustCompile(`\{(\w+)\}`)

// renderGitdirGlob renders rule's layout template into a "gitdir/i"
// pattern: every field the rule pins is substituted literally, every field
// it leaves open, including "project", which no rule carries, becomes "*",
// and the whole pattern is rooted at cfg.Root with a trailing "/**", so it
// also catches a repository whose remote was renamed or removed after
// gitcd cloned it there.
func renderGitdirGlob(cfg config.Config, rule config.Rule) string {
	tmpl := cfg.LayoutFor(rule.Host)
	rendered := placeholderPattern.ReplaceAllStringFunc(tmpl, func(m string) string {
		name := placeholderPattern.FindStringSubmatch(m)[1]
		switch name {
		case "host":
			return rule.Host
		case "owner", "org":
			if rule.Owner == "" {
				return "*"
			}
			return rule.Owner
		case "repo":
			if rule.Repo == "" {
				return "*"
			}
			return rule.Repo
		default:
			return "*"
		}
	})
	return filepath.Join(cfg.Root, rendered) + "/**"
}

// hasconfigGlobs returns one "hasconfig:remote.*.url" glob per URL form
// rule's host, owner and repo imply: the scp style SSH form and the HTTPS
// form, since the verified behaviour is that the glob matches the stored
// URL exactly as written, and the SSH and HTTPS forms of the same
// repository are written differently. When rule pins a repo, the owner
// and repo segment is matched literally, once with and once without a
// trailing ".git", since either is a valid stored remote; otherwise it
// ends in "**", to match every repository, and in the owner only case
// every owner-qualified path, under that host.
func hasconfigGlobs(rule config.Rule) []string {
	var globs []string
	for _, p := range repoPathVariants(rule.Owner, rule.Repo) {
		globs = append(globs, fmt.Sprintf("git@%s:%s", rule.Host, p))
		globs = append(globs, fmt.Sprintf("https://%s/%s", rule.Host, p))
	}
	return globs
}

func repoPathVariants(owner, repo string) []string {
	switch {
	case repo != "":
		base := owner + "/" + repo
		return []string{base, base + ".git"}
	case owner != "":
		return []string{owner + "/**"}
	default:
		return []string{"**"}
	}
}

// splitKey splits a profile's "section.key" or "section.subsection.key"
// git config key into its parts, consistent with the "section.key"
// validation internal/config already applies to every profile key.
func splitKey(key string) (section, subsection, name string, err error) {
	first := strings.Index(key, ".")
	last := strings.LastIndex(key, ".")
	if first <= 0 || last == len(key)-1 {
		return "", "", "", fmt.Errorf("gitconfig: %q is not a \"section.key\" git config key", key)
	}
	if first == last {
		return key[:first], "", key[first+1:], nil
	}
	return key[:first], key[first+1 : last], key[last+1:], nil
}

// quoteValue double quotes value for use as a git config value or path,
// escaping the two characters quoting itself introduces. Quoting is always
// valid git config syntax, so this never needs to special case a value
// that happens not to need it.
func quoteValue(value string) string {
	escaped := strings.ReplaceAll(value, `\`, `\\`)
	escaped = strings.ReplaceAll(escaped, `"`, `\"`)
	return `"` + escaped + `"`
}
